"""
build_plugin.py — Zero-Dependency Bundler for Horizon LifeOS Obsidian Plugin

Bundles obsidian-plugin/src/*.js into a self-contained CommonJS plugin
at obsidian-plugin/horizon-lifeos/{manifest.json, main.js, styles.css}.

Run with: py obsidian-plugin/build_plugin.py
"""

from pathlib import Path
import json
import re
import shutil
import subprocess

PLUGIN_DIR = Path(__file__).resolve().parent
SRC_DIR = PLUGIN_DIR / "src"
OUT_DIR = PLUGIN_DIR / "horizon-lifeos"

MODULE_ORDER = [
    ("logic-core", SRC_DIR / "logic-core.js"),
    ("markdown-codec", SRC_DIR / "markdown-codec.js"),
    ("vault-adapter", SRC_DIR / "vault-adapter.js"),
    ("horizon-view", SRC_DIR / "horizon-view.js"),
    ("settings", SRC_DIR / "settings.js"),
    ("main-entry", SRC_DIR / "main-entry.js"),
]

FORBIDDEN_PATTERNS = [
    (re.compile(r"\blocalStorage\b"), "localStorage is forbidden in mobile-safe Obsidian plugin code"),
    (re.compile(r"\bindexedDB\b"), "indexedDB is forbidden in mobile-safe Obsidian plugin code"),
    (re.compile(r"\bshowOpenFilePicker\b"), "showOpenFilePicker is forbidden in Obsidian plugin code"),
    (re.compile(r"\bshowSaveFilePicker\b"), "showSaveFilePicker is forbidden in Obsidian plugin code"),
    (re.compile(r"^\s*(?:import|export)\s+", re.MULTILINE), "ESM import/export statements are not allowed in CommonJS source modules"),
]

REQUIRE_RE = re.compile(r"""\brequire\s*\(\s*(['"])([^'"]+)\1\s*\)""")
ALLOWED_EXTERNALS = {"obsidian"}
ALLOWED_INTERNALS = {f"./{name}" for name, _ in MODULE_ORDER} | {f"./{name}.js" for name, _ in MODULE_ORDER}


def validate_module_source(name: str, src: str) -> None:
    for pattern, msg in FORBIDDEN_PATTERNS:
        if pattern.search(src):
            raise RuntimeError(f"[{name}.js] Hygiene check failed: {msg}")

    for match in REQUIRE_RE.finditer(src):
        target = match.group(2)
        if target not in ALLOWED_EXTERNALS and target not in ALLOWED_INTERNALS:
            raise RuntimeError(f"[{name}.js] Disallowed require('{target}') for mobile-compatible build.")


def build_plugin() -> Path:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    manifest_src = PLUGIN_DIR / "manifest.json"
    styles_src = SRC_DIR / "styles.css"
    manifest_data = json.loads(manifest_src.read_text(encoding="utf-8"))
    if manifest_data.get("isDesktopOnly") is not False:
        raise RuntimeError("manifest.json must set isDesktopOnly: false for Windows + iPhone compatibility.")

    module_blocks = []
    for name, path in MODULE_ORDER:
        raw = path.read_text(encoding="utf-8")
        validate_module_source(name, raw)
        indented = "\n".join(f"      {line}" if line else "" for line in raw.splitlines())
        module_blocks.append(
            f'    "./{name}": function (module, exports, require) {{\n{indented}\n    }}'
        )

    bundle = (
        "/*\n"
        " * Horizon LifeOS (GTD + PARA) — Built Obsidian Plugin Bundle\n"
        " * Generated by obsidian-plugin/build_plugin.py — do not edit directly.\n"
        " */\n"
        "(function () {\n"
        '  "use strict";\n'
        '  var __hostRequire = typeof require === "function" ? require : null;\n'
        "  var __modules = {\n"
        + ",\n".join(module_blocks)
        + "\n  };\n"
        "  var __cache = {};\n"
        "  function __require(id) {\n"
        '    if (id === "obsidian") {\n'
        "      if (__hostRequire) return __hostRequire(\"obsidian\");\n"
        '      throw new Error("Obsidian runtime API unavailable");\n'
        "    }\n"
        '    var key = String(id || "").replace(/\\.js$/, "");\n'
        "    if (__cache[key]) return __cache[key].exports;\n"
        "    var factory = __modules[key];\n"
        '    if (!factory) throw new Error("Unknown bundled module: " + id);\n'
        "    var mod = { exports: {} };\n"
        "    __cache[key] = mod;\n"
        "    factory(mod, mod.exports, __require);\n"
        "    return mod.exports;\n"
        "  }\n"
        '  module.exports = __require("./main-entry");\n'
        "})();\n"
    )

    main_out = OUT_DIR / "main.js"
    main_out.write_text(bundle, encoding="utf-8")
    shutil.copyfile(manifest_src, OUT_DIR / "manifest.json")
    shutil.copyfile(styles_src, OUT_DIR / "styles.css")

    # Syntax-check generated CommonJS bundle with Node if installed
    node_exe = shutil.which("node")
    if node_exe:
        res = subprocess.run([node_exe, "--check", str(main_out)], capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"Generated main.js failed node --check:\n{res.stderr}")

    return main_out


if __name__ == "__main__":
    out_file = build_plugin()
    size_kb = out_file.stat().st_size / 1024
    print(f"Built Horizon LifeOS plugin ({size_kb:.2f} KB) -> {OUT_DIR}")
